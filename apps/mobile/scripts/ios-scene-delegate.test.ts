import { createRequire } from "node:module";
import { describe, expect, it } from "vitest";

const require = createRequire(import.meta.url);
const { applySceneDelegate, applySceneManifest } =
	require("../plugins/with-ios-scene-delegate.cjs") as {
		applySceneDelegate(source: string): string;
		applySceneManifest(plist: Record<string, unknown>): Record<string, unknown>;
	};

// Expo SDK 55's factory-based Swift template. Keep the lifecycle and linking
// methods together so a migration cannot silently discard another plugin's work.
const appDelegate = `import Expo
import React
import ReactAppDependencyProvider
@main
class AppDelegate: ExpoAppDelegate {
  var window: UIWindow?
  var reactNativeDelegate: ExpoReactNativeFactoryDelegate?
  var reactNativeFactory: RCTReactNativeFactory?
  public override func application(
    _ application: UIApplication,
    didFinishLaunchingWithOptions launchOptions: [UIApplication.LaunchOptionsKey: Any]? = nil
  ) -> Bool {
    let delegate = ReactNativeDelegate()
    let factory = ExpoReactNativeFactory(delegate: delegate)
    delegate.dependencyProvider = RCTAppDependencyProvider()
    reactNativeDelegate = delegate
    reactNativeFactory = factory
#if os(iOS) || os(tvOS)
    window = UIWindow(frame: UIScreen.main.bounds)
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions)
#endif
    return super.application(application, didFinishLaunchingWithOptions: launchOptions)
  }
  // Other plugins and Expo linking overrides remain here.
}
class ReactNativeDelegate: ExpoReactNativeFactoryDelegate {}
`;

describe("iOS scene lifecycle prebuild plugin", () => {
	it("moves a clean Expo launch into a scene window and preserves the application delegate", () => {
		const migrated = applySceneDelegate(appDelegate);
		expect(migrated).not.toContain("UIScreen.main.bounds");
		expect(migrated).toContain("UIWindow(windowScene: windowScene)");
		expect(migrated).toContain("appDelegate.window = window");
		expect(migrated.match(/factory\.startReactNative\(/g)).toHaveLength(1);
		expect(migrated).toContain(
			"return super.application(application, didFinishLaunchingWithOptions: launchOptions)",
		);
		expect(migrated).toContain(
			"// Other plugins and Expo linking overrides remain here.",
		);
		expect(migrated).toContain(
			"class ReactNativeDelegate: ExpoReactNativeFactoryDelegate {}",
		);
	});
	it("forwards cold and warm custom URLs and universal links through Expo and React Native", () => {
		const migrated = applySceneDelegate(appDelegate);
		const seed = migrated.indexOf("// Seed Expo Linking");
		expect(seed).toBeLessThan(migrated.indexOf("factory.startReactNative("));
		expect(migrated).toContain("launchOptions[.url] = context.url");
		expect(migrated).toContain("launchOptions[.userActivityDictionary]");
		expect(migrated).toContain(
			"openURLContexts URLContexts: Set<UIOpenURLContext>",
		);
		expect(migrated).toContain("continue userActivity: NSUserActivity");
		expect(migrated).toContain(
			"appDelegate.application(UIApplication.shared, open: context.url",
		);
		expect(migrated).toContain(
			"appDelegate.application(UIApplication.shared, continue: activity",
		);
	});
	it("is idempotent across repeated prebuilds, including the existing local wrapper", () => {
		const migrated = applySceneDelegate(appDelegate);
		expect(applySceneDelegate(migrated)).toBe(migrated);
		const unmarked = migrated.replace(
			"// Cline scene lifecycle: generated by with-ios-scene-delegate.\n",
			"",
		);
		expect(applySceneDelegate(unmarked)).toBe(unmarked);
	});
	it("fails visibly on an unfamiliar template instead of enabling a broken scene manifest", () => {
		expect(() => applySceneDelegate("class AppDelegate: NSObject {} ")).toThrow(
			"Expo Swift AppDelegate",
		);
		expect(() =>
			applySceneDelegate(
				appDelegate.replace("in: window,", "in: differentWindow,"),
			),
		).toThrow("could not migrate");
		expect(() =>
			applySceneDelegate(
				appDelegate.replace(/#if os\(iOS\)[\s\S]*?#endif/, ""),
			),
		).toThrow("unexpected AppDelegate");
	});
	it("registers one scene without discarding other Info.plist settings", () => {
		const plist = {
			CFBundleURLTypes: [{ CFBundleURLSchemes: ["clinecode"] }],
			UIApplicationSceneManifest: {
				CustomKey: true,
				UISceneConfigurations: { ExternalDisplay: [{ Name: "Other" }] },
			},
		};
		const migrated = applySceneManifest(plist);
		expect(migrated).toMatchObject({
			CFBundleURLTypes: plist.CFBundleURLTypes,
			UIApplicationSceneManifest: {
				CustomKey: true,
				UIApplicationSupportsMultipleScenes: false,
				UISceneConfigurations: {
					ExternalDisplay: [{ Name: "Other" }],
					UIWindowSceneSessionRoleApplication: [
						{
							UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate",
						},
					],
				},
			},
		});
		expect(applySceneManifest(migrated)).toEqual(migrated);
	});
});
