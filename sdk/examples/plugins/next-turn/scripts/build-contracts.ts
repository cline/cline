/**
 * Generate the JSON Schemas Next Turn publishes, into `contracts/`:
 *
 *   bun run scripts/build-contracts.ts          regenerate contracts/
 *   bun run scripts/build-contracts.ts --check  fail when contracts/ is stale
 *
 * The schemas are hand-built JSON Schema in `src/contracts.ts` (not zod), so
 * they are written as given. Output is deterministic: running twice yields
 * the same bytes. Patch the constants in `src/`, not the artifacts.
 */
import {
	existsSync,
	mkdirSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { CONTRACTS_SCRIPT, CONTRACTS_SOURCE } from "../src/config";
import {
	CONTRACT_ID_BASE,
	CONTRACT_SCHEMA_DIALECT,
	NEXT_TURN_SCHEMAS,
} from "../src/contracts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "contracts");
const check = process.argv.includes("--check");

function schemaFileName(name: string): string {
	return `${name}.schema.json`;
}

function writeJson(path: string, value: unknown, stale: string[]): void {
	const body = `${JSON.stringify(value, null, "\t")}\n`;
	if (check) {
		if (!existsSync(path)) {
			stale.push(path);
			return;
		}
		try {
			const current = `${JSON.stringify(JSON.parse(readFileSync(path, "utf8")), null, "\t")}\n`;
			if (current !== body) stale.push(path);
		} catch {
			stale.push(path);
		}
		return;
	}
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, body);
}

const stale: string[] = [];
if (!check) {
	rmSync(outDir, { recursive: true, force: true });
	mkdirSync(outDir, { recursive: true });
}
for (const entry of NEXT_TURN_SCHEMAS) {
	const file = schemaFileName(entry.name);
	writeJson(
		join(outDir, file),
		{
			$schema: CONTRACT_SCHEMA_DIALECT,
			$id: `${CONTRACT_ID_BASE}${file}`,
			title: entry.name,
			description: entry.about,
			...entry.schema,
		},
		stale,
	);
}
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8")) as {
	version: string;
};
writeJson(
	join(outDir, "index.json"),
	{
		$comment: `GENERATED by ${CONTRACTS_SCRIPT} — do not edit.`,
		generator: CONTRACTS_SCRIPT,
		source: CONTRACTS_SOURCE,
		pluginVersion: pkg.version,
		jsonSchema: "draft-2020-12",
		schemas: NEXT_TURN_SCHEMAS.map((entry) => ({
			name: entry.name,
			file: schemaFileName(entry.name),
			io: entry.io,
			about: entry.about,
		})),
	},
	stale,
);

if (check) {
	if (stale.length > 0) {
		console.error(
			`contracts are stale: ${stale.join(", ")} — run bun run contracts`,
		);
		process.exit(1);
	}
	console.log(`contracts: ${NEXT_TURN_SCHEMAS.length} schemas current`);
} else {
	console.log(
		`contracts: ${NEXT_TURN_SCHEMAS.length} JSON Schemas → contracts/`,
	);
}
