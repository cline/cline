/**
 * Generate the JSON Schemas Next Turn publishes, into `contracts/`:
 *
 *   bun run scripts/build-contracts.ts          regenerate contracts/
 *   bun run scripts/build-contracts.ts --check  fail when contracts/ is stale
 *
 * The schemas are hand-built JSON Schema in `src/contracts.ts` (not zod), so
 * they are written as given. Patch the constants in `src/`, not the artifacts.
 */
import {
	existsSync,
	mkdirSync,
	readdirSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { NEXT_TURN_SCHEMAS } from "../src/contracts";
import { PLUGIN_ROOT } from "./build";

const CONTRACTS_SCRIPT = "scripts/build-contracts.ts";
const CONTRACTS_SOURCE = "src/contracts.ts";
const CONTRACT_SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema";
const CONTRACT_ID_BASE = "https://cline.bot/next-turn/";

const outDir = join(PLUGIN_ROOT, "contracts");
const check = process.argv.includes("--check");
const expected = new Set<string>();
const stale: string[] = [];

/** Writes `value`, or under `--check` notes the file as stale when its JSON differs; whitespace is ignored, key order is not. */
function writeJson(file: string, value: unknown): void {
	expected.add(file);
	const path = join(outDir, file);
	const body = JSON.stringify(value, null, "\t");
	if (!check) {
		writeFileSync(path, `${body}\n`);
		return;
	}
	try {
		const current = JSON.parse(readFileSync(path, "utf8"));
		if (JSON.stringify(current, null, "\t") === body) return;
	} catch {}
	stale.push(path);
}

if (!check) {
	rmSync(outDir, { recursive: true, force: true });
	mkdirSync(outDir, { recursive: true });
}
const schemas = NEXT_TURN_SCHEMAS.map((entry) => ({
	...entry,
	file: `${entry.name}.schema.json`,
}));
for (const entry of schemas) {
	writeJson(entry.file, {
		$schema: CONTRACT_SCHEMA_DIALECT,
		$id: `${CONTRACT_ID_BASE}${entry.file}`,
		title: entry.name,
		description: entry.about,
		...entry.schema,
	});
}
const pkg = JSON.parse(
	readFileSync(join(PLUGIN_ROOT, "package.json"), "utf8"),
) as {
	version: string;
};
writeJson("index.json", {
	$comment: `GENERATED by ${CONTRACTS_SCRIPT} — do not edit.`,
	generator: CONTRACTS_SCRIPT,
	source: CONTRACTS_SOURCE,
	pluginVersion: pkg.version,
	jsonSchema: "draft-2020-12",
	schemas: schemas.map(({ name, file, io, about }) => ({
		name,
		file,
		io,
		about,
	})),
});

if (check) {
	const present = existsSync(outDir) ? readdirSync(outDir) : [];
	for (const file of present)
		if (!expected.has(file) && !file.startsWith("."))
			stale.push(join(outDir, file));
	if (stale.length > 0) {
		console.error(
			`contracts are stale: ${stale.join(", ")} — run bun run contracts`,
		);
		process.exit(1);
	}
	console.log(`contracts: ${NEXT_TURN_SCHEMAS.length} schemas current`);
} else {
	console.log(
		`contracts: ${NEXT_TURN_SCHEMAS.length} JSON Schemas → contracts/`,
	);
}
