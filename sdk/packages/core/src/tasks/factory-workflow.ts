import type {
	AgendaTaskRecord,
	AgendaTaskRunRecord,
	FactoryAgent,
	FactoryArtifact,
	FactoryCandidate,
	FactoryRunState,
} from "@cline/shared";
import { DEFAULT_FACTORY_AGENTS } from "@cline/shared";
import type {
	AgendaTaskRuntime,
	AgendaTaskRuntimeResult,
} from "./agenda-task-manager";
import {
	factoryReviewFindings,
	parseFactoryReview,
	resolveFactoryAgent,
} from "./factory-agents";
import {
	assertFactoryCandidate,
	captureFactoryArtifactVersions,
	checkpointFactoryWorkspace,
	collectFactoryArtifacts,
	publishFactoryPullRequest,
	verifyFactoryChecks,
} from "./factory-local";

export type FactoryWorkflowInput = {
	task: AgendaTaskRecord;
	run: AgendaTaskRunRecord;
	builderSessionId: string;
	state: FactoryRunState;
	runtime: AgendaTaskRuntime;
	storageDir: string;
	signal: AbortSignal;
	save: (state: FactoryRunState) => void;
	sessionStarted: (sessionId: string) => void;
	repairInstructions?: string;
};

export async function runFactoryWorkflow(
	input: FactoryWorkflowInput,
): Promise<AgendaTaskRuntimeResult> {
	const { task, run, runtime, signal } = input;
	const config = task.factory;
	if (!config) throw new Error("Factory configuration is required");
	const agents = config.agents ?? DEFAULT_FACTORY_AGENTS;
	let state = input.state;
	const save = (patch: Partial<FactoryRunState>) => {
		signal.throwIfAborted();
		state = { ...state, ...patch };
		input.save(state);
	};
	const workTask = {
		...task,
		cwd: state.workspace.path,
		workspaceRoot: state.workspace.path,
		assignee: undefined,
	};
	const execute = async (
		sessionId: string,
		instructions: string,
		agent: FactoryAgent,
	) => {
		signal.throwIfAborted();
		const result = await runtime.runSession(
			sessionId,
			resolveFactoryAgent({ ...workTask, instructions }, agent),
			run,
		);
		signal.throwIfAborted();
		if (result.status !== "completed")
			throw new Error(
				result.error ?? result.summary ?? "Factory session did not complete",
			);
		return result.summary ?? "";
	};
	const start = async (agent: FactoryAgent, role: "reviewer" | "verifier") => {
		signal.throwIfAborted();
		const session = await runtime.startSession(
			resolveFactoryAgent(workTask, agent),
			run,
			run.requestedByClientId,
			{ unattended: false, factoryRole: role },
		);
		input.sessionStarted(session.sessionId);
		if (signal.aborted) {
			await runtime.abortSession(
				session.sessionId,
				"Feature workflow cancelled",
			);
			signal.throwIfAborted();
		}
		save({
			sessions: [...state.sessions, { sessionId: session.sessionId, role }],
		});
		return session.sessionId;
	};
	const responseFormat =
		'Return only JSON matching {"verdict":"pass"|"changes_requested","summary":"...","findings":["..."],"coverage":{"static":["..."],"exercised":["..."],"unverified":["..."]}}; pass requires zero findings. If submit_and_exit is available, put that exact JSON in its summary field. Keep coverage private; never publish it.';
	try {
		save({ candidate: undefined });
		await execute(
			input.builderSessionId,
			`${task.instructions}${input.repairInstructions ? `\n\nPR FOLLOW-UP:\n${input.repairInstructions}` : ""}\n\nAPPROVED VERIFICATION CHECKS:\n${JSON.stringify(config.checks)}\nEvidence must be generated by these checks in gitignored paths. Do not modify approved checks or acceptance criteria.\n\nImplement only this approved scope. Reuse existing code. Avoid duplicated logic, speculative abstractions, unrelated changes, and comments that narrate code. Do not publish, push, or open a pull request. The factory will run the approved checks and independent review.`,
			agents.implementer,
		);
		while (true) {
			save({
				phase: "verifying",
				candidate: undefined,
			});
			const { candidateCommit, diff } = await checkpointFactoryWorkspace({
				workspace: state.workspace,
				signal,
			});
			let candidate: FactoryCandidate = {
				commit: candidateCommit,
				checks: [],
				reviews: [],
			};
			save({ candidate });
			const checks = await verifyFactoryChecks({
				checks: config.checks,
				workspace: state.workspace,
				candidateCommit,
				storageDir: input.storageDir,
				runId: run.runId,
				signal,
				timeoutMs: (task.timeoutSeconds ?? 600) * 1000,
			});
			candidate = { ...candidate, checks };
			save({ candidate });
			const findings = checks
				.filter((check) => check.status !== "passed")
				.map((check) => `${check.name}: ${check.status}\n${check.output}`);

			if (findings.length === 0 && agents.verifier) {
				const declaredPaths = agents.verifier.artifacts ?? [];
				const previousVersions = await captureFactoryArtifactVersions(
					state.workspace.path,
					declaredPaths,
				);
				const sessionId = await start(agents.verifier, "verifier");
				const response = await execute(
					sessionId,
					`Verify the approved behavior by running the existing application and test harness using available tools. Search for and reuse the project's existing verification scripts. Do not modify tracked source or tests. Do not fabricate screenshots or claim interactions you did not perform. Generate fresh screenshot or recording evidence at these gitignored worktree paths: ${JSON.stringify(declaredPaths)}. Report unavailable tools and unverified behavior as blocking findings. ${responseFormat}\n\nAPPROVED BRIEF:\n${task.instructions}\nCANDIDATE COMMIT: ${candidateCommit}\nCHECK EVIDENCE:\n${JSON.stringify(checks)}`,
					agents.verifier,
				);
				await assertFactoryCandidate({
					workspace: state.workspace,
					candidateCommit,
					signal,
				});
				let review = parseFactoryReview(response);
				let artifacts: FactoryArtifact[] = [];
				if (factoryReviewFindings(review).length === 0) {
					try {
						artifacts = await collectFactoryArtifacts({
							cwd: state.workspace.path,
							declaredPaths,
							previousVersions,
							storageDir: input.storageDir,
							runId: run.runId,
						});
					} catch (error) {
						review = {
							...review,
							verdict: "changes_requested",
							summary: "Verifier evidence could not be collected.",
							findings: [
								error instanceof Error ? error.message : String(error),
							],
						};
					}
				}
				candidate = {
					...candidate,
					verification: { sessionId, review, artifacts },
				};
				save({ candidate });
				findings.push(
					...factoryReviewFindings(review).map(
						(finding) => `Verification: ${finding}`,
					),
				);
			}
			if (findings.length === 0) {
				save({ phase: "reviewing" });
				for (const [reviewerIndex, agent] of agents.reviewers.entries()) {
					const sessionId = await start(agent, "reviewer");
					const response = await execute(
						sessionId,
						`Independently review this candidate against the approved brief. Search affected modules for existing helpers and equivalent operations, and read a representative implementation before judging departures. Assess correctness and maintainability separately, with concrete examples and a distinction between worthwhile cleanup and subjective style. Challenge duplicated logic, unnecessary abstractions or state, speculative compatibility, redundant defensive checks, opaque parameters, and avoidable branching. Identify the current requirement and smallest clearer behavior-preserving alternative. Review tests for distinct meaningful behavior and comments for intent, invariants, or protocol constraints rather than narration. Trace every changed return value, event payload, and persisted structure through producer -> transformation -> consumer, including tool-specific handlers, UI renderers, accounting, and restore/resume. Compare below/above thresholds, including built-in orchestration and external/custom tools. Verify actual user-visible consequences; distinguish static, exercised, and unverified coverage. Do not consult other reviewers' conclusions. Do not change files. Never treat passing tests as proof of correctness. ${responseFormat}\n\nAPPROVED BRIEF:\n${task.instructions}${input.repairInstructions ? `\n\nVerify this feedback without broadening scope:\n${input.repairInstructions}` : ""}\n\nCANDIDATE COMMIT: ${candidateCommit}\nCHECK EVIDENCE:\n${JSON.stringify(checks)}\nVERIFICATION EVIDENCE:\n${JSON.stringify(candidate.verification)}\n\nFULL DIFF:\n${diff}`,
						agent,
					);
					await assertFactoryCandidate({
						workspace: state.workspace,
						candidateCommit,
						signal,
					});
					const review = parseFactoryReview(response);
					candidate = {
						...candidate,
						reviews: [
							...candidate.reviews,
							{ reviewerIndex, sessionId, review },
						],
					};
					save({ candidate });
					findings.push(
						...factoryReviewFindings(review).map(
							(finding) => `Reviewer ${reviewerIndex + 1}: ${finding}`,
						),
					);
				}
			}
			await assertFactoryCandidate({
				workspace: state.workspace,
				candidateCommit,
				signal,
			});
			if (findings.length === 0) {
				if (config.publishPullRequest && !input.repairInstructions) {
					save({ phase: "publishing" });
					const pullRequestUrl = await publishFactoryPullRequest({
						workspace: state.workspace,
						candidateCommit,
						title: task.title,
						body: `Candidate ${candidateCommit} completed the approved verification checks and independent code review. Review the diff and local evidence in the feature task before merging.`,
						signal,
					});
					save({ pullRequestUrl });
				}
				let pullRequestWatch = state.pullRequestWatch;
				if (input.repairInstructions && pullRequestWatch?.pending) {
					pullRequestWatch = {
						...pullRequestWatch,
						pending: { ...pullRequestWatch.pending, phase: "publish" },
					};
				} else if (config.watchPullRequest && state.pullRequestUrl) {
					pullRequestWatch = {
						headCommit: candidateCommit,
						handledFeedbackIds: [],
					};
				}
				save({
					phase: pullRequestWatch ? "watching" : "ready",
					pullRequestWatch,
				});
				return {
					status: "completed",
					summary: `Verified candidate ${candidateCommit}. ${config.publishPullRequest ? "Draft pull request ready for review." : "Changes ready for review; publishing is disabled."}`,
				};
			}
			if (state.repairRound >= config.maxRepairRounds)
				throw new Error(
					`Repair limit (${config.maxRepairRounds}) reached.\n${findings.join("\n\n")}`,
				);
			save({
				phase: "repairing",
				repairRound: state.repairRound + 1,
				candidate: undefined,
			});
			await execute(
				input.builderSessionId,
				`Address these consolidated blocking findings within the approved scope. Do not weaken checks or acceptance criteria, publish, push, or open a PR.\n\n${findings.join("\n\n")}`,
				agents.implementer,
			);
		}
	} catch (error) {
		const message = error instanceof Error ? error.message : String(error);
		if (!signal.aborted)
			save({
				phase: "blocked",
				error: message,
				pullRequestWatch: state.pullRequestWatch?.pending
					? {
							...state.pullRequestWatch,
							pending: { ...state.pullRequestWatch.pending, phase: "blocked" },
						}
					: state.pullRequestWatch,
			});
		throw error;
	}
}
