import type {
	AgendaTaskRecord,
	AgendaTaskRunRecord,
	FactoryRunState,
} from "@cline/shared";
import { factoryReviewSchema } from "@cline/shared";
import type {
	AgendaTaskRuntime,
	AgendaTaskRuntimeResult,
} from "./agenda-task-manager";
import {
	assertFactoryCandidate,
	checkpointFactoryWorkspace,
	publishFactoryPullRequest,
	verifyFactoryChecks,
} from "./factory-local";

export async function runFactoryWorkflow(input: {
	task: AgendaTaskRecord;
	run: AgendaTaskRunRecord;
	builderSessionId: string;
	state: FactoryRunState;
	runtime: AgendaTaskRuntime;
	storageDir: string;
	signal: AbortSignal;
	save: (state: FactoryRunState) => void;
	sessionStarted: (sessionId: string) => void;
}): Promise<AgendaTaskRuntimeResult> {
	const { task, run, runtime, signal } = input;
	const config = task.factory;
	if (!config) throw new Error("Factory configuration is required");
	let state = input.state;
	const save = (patch: Partial<FactoryRunState>) => {
		signal.throwIfAborted();
		state = { ...state, ...patch };
		input.save(state);
	};
	const workTask = {
		...task,
		cwd: state.workspace.path,
		workspaceRoot: state.workspace.path,
		assignee: undefined,
	};
	const execute = async (sessionId: string, instructions: string) => {
		signal.throwIfAborted();
		const result = await runtime.runSession(
			sessionId,
			{ ...workTask, instructions },
			run,
		);
		signal.throwIfAborted();
		if (result.status !== "completed")
			throw new Error(
				result.error ?? result.summary ?? "Factory session did not complete",
			);
		return result.summary ?? "";
	};
	try {
		await execute(
			input.builderSessionId,
			`${task.instructions}\n\nAPPROVED VERIFICATION CHECKS:\n${JSON.stringify(config.checks)}\nEvidence must be generated by these checks in gitignored paths. Do not modify approved checks or acceptance criteria.\n\nImplement only this approved scope. Reuse existing code. Avoid duplicated logic, speculative abstractions, unrelated changes, and comments that narrate code. Do not publish, push, or open a pull request. The factory will run the approved checks and independent review.`,
		);
		while (true) {
			save({
				phase: "verifying",
				checks: [],
				review: undefined,
				candidateCommit: undefined,
			});
			const { candidateCommit, diff } = await checkpointFactoryWorkspace({
				workspace: state.workspace,
				signal,
			});
			save({ candidateCommit });
			const checks = await verifyFactoryChecks({
				checks: config.checks,
				workspace: state.workspace,
				candidateCommit,
				storageDir: input.storageDir,
				runId: run.runId,
				signal,
				timeoutMs: (task.timeoutSeconds ?? 600) * 1000,
			});
			save({ checks });
			let findings = checks
				.filter((check) => check.status !== "passed")
				.map((check) => `${check.name}: ${check.status}\n${check.output}`);
			if (findings.length === 0) {
				save({ phase: "reviewing" });
				const reviewer = await runtime.startSession(
					workTask,
					run,
					run.requestedByClientId,
					{ unattended: false, factoryRole: "reviewer" },
				);
				input.sessionStarted(reviewer.sessionId);
				if (signal.aborted) {
					await runtime.abortSession(
						reviewer.sessionId,
						"Feature workflow cancelled",
					);
					signal.throwIfAborted();
				}
				save({
					sessions: [
						...state.sessions,
						{ sessionId: reviewer.sessionId, role: "reviewer" },
					],
				});
				const response = await execute(
					reviewer.sessionId,
					`Independently review this candidate against the approved brief. Assess correctness and maintainability separately: duplicated logic, unnecessary abstractions/state, unrelated changes, weak or redundant tests, and comments that merely narrate code. Trace changed producer/transformation/consumer paths and restore behavior. Report concrete blocking findings with smallest clearer alternatives. Do not change files. Never treat passing tests as proof of correctness. Return only JSON matching {"verdict":"pass"|"changes_requested","summary":"...","findings":["..."]}; pass requires zero findings. If submit_and_exit is available, put that exact JSON in its summary field.\n\nAPPROVED BRIEF:\n${task.instructions}\n\nCANDIDATE COMMIT: ${candidateCommit}\nCHECK EVIDENCE:\n${JSON.stringify(checks)}\n\nFULL DIFF:\n${diff}`,
				);
				const review = factoryReviewSchema.parse(
					JSON.parse(
						response
							.replace(/^\s*```(?:json)?\s*\n?/, "")
							.replace(/\n?```\s*$/, ""),
					),
				);
				save({ review });
				findings =
					review.verdict === "pass" && review.findings.length === 0
						? []
						: review.findings.length
							? review.findings
							: [review.summary];
			}
			await assertFactoryCandidate({
				workspace: state.workspace,
				candidateCommit,
				signal,
			});
			if (findings.length === 0) {
				if (config.publishPullRequest) {
					save({ phase: "publishing" });
					const pullRequestUrl = await publishFactoryPullRequest({
						workspace: state.workspace,
						candidateCommit,
						title: task.title,
						body: `Candidate ${candidateCommit} completed the approved verification checks and independent code review. Review the diff and local evidence in the feature task before merging.`,
						signal,
					});
					save({ pullRequestUrl });
				}
				save({ phase: "ready" });
				return {
					status: "completed",
					summary: `Verified candidate ${candidateCommit}. ${config.publishPullRequest ? "Draft pull request ready for review." : "Changes ready for review; publishing is disabled."}`,
				};
			}
			if (state.repairRound >= config.maxRepairRounds)
				throw new Error(
					`Repair limit (${config.maxRepairRounds}) reached.\n${findings.join("\n\n")}`,
				);
			save({ phase: "repairing", repairRound: state.repairRound + 1 });
			await execute(
				input.builderSessionId,
				`Address these consolidated blocking findings within the approved scope. Do not weaken checks or acceptance criteria, publish, push, or open a PR.\n\n${findings.join("\n\n")}`,
			);
		}
	} catch (error) {
		const message = error instanceof Error ? error.message : String(error);
		if (!signal.aborted) save({ phase: "blocked", error: message });
		throw error;
	}
}
